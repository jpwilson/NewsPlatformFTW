/**
 * Generates api/_lib/site-shell.js: the static header and footer markup of
 * the prerendered marketing pages (client/src/content/shell.ts), as plain
 * strings the serverless functions can use without importing TypeScript.
 * The /latest archive and the channel crawler pages wear the same shell.
 *
 *   npx tsx scripts/gen-site-shell.ts           # write the module
 *   npx tsx scripts/gen-site-shell.ts --check   # exit 1 if it is out of date
 *
 * scripts/check-seo.mjs runs the --check form, so a change to the footer
 * links or the header that is not regenerated fails the build checks.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { renderFooterHtml, renderHeaderHtml } from "../client/src/content/shell";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = path.join(ROOT, "api", "_lib", "site-shell.js");

/** The year changes at runtime, not at generation time. */
const YEAR = "{{YEAR}}";

export function siteShellModule(): string {
  const footer = renderFooterHtml().replace(`© ${new Date().getFullYear()} NewsPlatform`, `© ${YEAR} NewsPlatform`);
  if (!footer.includes(YEAR)) throw new Error("gen-site-shell: footer copyright line not found");
  return `// GENERATED by scripts/gen-site-shell.ts from client/src/content/shell.ts.
// Do not edit: change shell.ts or marketing.ts, then run \`npm run gen:shell\`.
// Plain strings, no imports (loaded by the serverless functions).

/** Header with "Latest stories" marked as the current page. */
export const SITE_HEADER_LATEST_HTML = ${JSON.stringify(renderHeaderHtml("/latest"))};

/** Header with no current page. */
export const SITE_HEADER_HTML = ${JSON.stringify(renderHeaderHtml(""))};

/** Footer; {{YEAR}} is replaced at render time. */
export const SITE_FOOTER_HTML = ${JSON.stringify(footer)};

/** Stylesheet written by scripts/prerender.ts: a stable-named copy of the built Tailwind CSS. */
export const SITE_STYLESHEET = "/site.css";
`;
}

const want = siteShellModule();
if (process.argv.includes("--check")) {
  const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";
  if (have !== want) {
    console.error("api/_lib/site-shell.js is out of date with client/src/content/shell.ts: run `npm run gen:shell`.");
    process.exit(1);
  }
  console.log("api/_lib/site-shell.js is up to date.");
} else {
  fs.writeFileSync(TARGET, want);
  console.log(`wrote ${path.relative(ROOT, TARGET)}`);
}
